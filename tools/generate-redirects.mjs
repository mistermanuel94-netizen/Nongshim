/**
 * Emit host redirect configuration from data/redirects.json.
 *
 * Static hosting cannot express 301s in the HTML, so the redirect map has to
 * become host configuration. Files are written into `dist/` (for hosts that
 * read a file from the publish directory) and into `deploy/` (for hosts
 * configured from the repository).
 *
 * Query-string sources are handled per host, because each expresses them
 * differently — that detail is the whole reason this is generated rather than
 * hand-maintained across four formats.
 */
import fs from 'node:fs/promises';
import path from 'node:path';

const DIST = 'dist';
const DEPLOY = 'deploy';

const split = (from) => {
  const [pathname, query] = from.split('?');
  return { pathname, query: query ?? null };
};

/* ---------------------------------------------------------- Netlify ------ */

function netlify(redirects) {
  const lines = [
    '# Generated by tools/generate-redirects.mjs — do not edit by hand.',
    '# Legacy URL -> new URL, all 301 (permanent).',
    '',
  ];
  for (const r of redirects) {
    const { pathname, query } = split(r.from);
    if (query) {
      // Netlify matches query params as named conditions on the same line.
      const params = [...new URLSearchParams(query).entries()].map(([k, v]) => `${k}=${v}`).join(' ');
      lines.push(`${pathname} ${params} ${r.to} ${r.status}!`);
    } else {
      lines.push(`${pathname} ${r.to} ${r.status}!`);
    }
  }
  // A trailing catch-all so unmatched paths get the custom 404 with a real
  // 404 status rather than the host's default page.
  lines.push('', '/* /404.html 404');
  return lines.join('\n') + '\n';
}

/* ----------------------------------------------------------- Vercel ------ */

function vercel(redirects) {
  return (
    JSON.stringify(
      {
        $schema: 'https://openapi.vercel.sh/vercel.json',
        trailingSlash: true,
        redirects: redirects.map((r) => {
          const { pathname, query } = split(r.from);
          const rule = { source: pathname, destination: r.to, permanent: r.status === 301 };
          if (query) {
            rule.has = [...new URLSearchParams(query).entries()].map(([key, value]) => ({
              type: 'query',
              key,
              value,
            }));
          }
          return rule;
        }),
      },
      null,
      2
    ) + '\n'
  );
}

/* ------------------------------------------------- Cloudflare Pages ------ */

function cloudflare(redirects) {
  // Cloudflare's _redirects ignores the query string when matching, so
  // query-only sources are emitted as a comment listing what a Worker or the
  // Bulk Redirects product must handle instead. Silently dropping them would
  // leave 1,000+ legacy URLs unresolved.
  const pathOnly = redirects.filter((r) => !r.from.includes('?'));
  const queryBased = redirects.filter((r) => r.from.includes('?'));
  const lines = [
    '# Generated by tools/generate-redirects.mjs — do not edit by hand.',
    '',
    ...pathOnly.map((r) => `${r.from} ${r.to} ${r.status}`),
    '',
    `# ${queryBased.length} redirects match on the query string, which _redirects`,
    '# cannot express. Load deploy/redirects.csv into Cloudflare Bulk Redirects,',
    '# or handle them in a Worker. See docs/redirects.md.',
    '',
    '/* /404.html 404',
  ];
  return lines.join('\n') + '\n';
}

/* ------------------------------------------------------------ Apache ----- */

function apache(redirects) {
  const lines = [
    '# Generated by tools/generate-redirects.mjs — do not edit by hand.',
    'RewriteEngine On',
    '',
  ];
  for (const r of redirects) {
    const { pathname, query } = split(r.from);
    const escaped = pathname.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    if (query) {
      const cond = query.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      lines.push(`RewriteCond %{QUERY_STRING} ^${cond}$`);
      lines.push(`RewriteRule ^${escaped.replace(/^\//, '')}$ ${r.to}? [R=${r.status},L]`);
    } else {
      lines.push(`RewriteRule ^${escaped.replace(/^\//, '')}$ ${r.to} [R=${r.status},L]`);
    }
  }
  return lines.join('\n') + '\n';
}

/* ------------------------------------------------------------- Nginx ----- */

function nginx(redirects) {
  const pathOnly = redirects.filter((r) => !r.from.includes('?'));
  const byPath = new Map();
  for (const r of redirects) {
    if (!r.from.includes('?')) continue;
    const { pathname } = split(r.from);
    if (!byPath.has(pathname)) byPath.set(pathname, []);
    byPath.get(pathname).push(r);
  }

  const lines = [
    '# Generated by tools/generate-redirects.mjs — do not edit by hand.',
    '# Include inside the server block.',
    '',
    'location = / { }',
    '',
    '# --- path-only redirects ---',
    ...pathOnly.map((r) => `location = ${r.from} { return ${r.status} ${r.to}; }`),
    '',
    '# --- query-string redirects ---',
  ];

  for (const [pathname, rules] of byPath) {
    lines.push(`location = ${pathname} {`);
    for (const r of rules) {
      const { query } = split(r.from);
      lines.push(`  if ($args = "${query}") { return ${r.status} ${r.to}; }`);
    }
    lines.push('}');
  }
  return lines.join('\n') + '\n';
}

/* -------------------------------------------------------------- Headers -- */

/**
 * Security and caching headers. Static assets carry content hashes in their
 * filenames, so they are immutable; HTML must always revalidate.
 *
 * The CSP allows only what the site actually loads: its own styles and
 * scripts, its own images, and YouTube frames on the video page. There are no
 * third-party scripts to allow.
 */
const CSP = [
  "default-src 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  // Astro inlines small stylesheets and emits inline <style> for scoped CSS.
  "style-src 'self' 'unsafe-inline'",
  "script-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  // Office maps and the video library.
  'frame-src https://www.google.com https://www.youtube-nocookie.com https://www.youtube.com',
  'upgrade-insecure-requests',
].join('; ');

const HEADER_LINES = [
  ['X-Content-Type-Options', 'nosniff'],
  ['Referrer-Policy', 'strict-origin-when-cross-origin'],
  ['X-Frame-Options', 'DENY'],
  ['Permissions-Policy', 'camera=(), microphone=(), geolocation=(), interest-cohort=()'],
  ['Strict-Transport-Security', 'max-age=63072000; includeSubDomains; preload'],
  ['Content-Security-Policy', CSP],
];

function headersFile() {
  return [
    '# Generated by tools/generate-redirects.mjs — do not edit by hand.',
    '',
    '/*',
    ...HEADER_LINES.map(([k, v]) => `  ${k}: ${v}`),
    '',
    '# Hashed asset filenames are immutable.',
    '/_assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    '/fonts/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    '# HTML must revalidate so a redeploy is picked up immediately.',
    '/*.html',
    '  Cache-Control: public, max-age=0, must-revalidate',
    '',
    '/',
    '  Cache-Control: public, max-age=0, must-revalidate',
    '',
  ].join('\n');
}

/* ----------------------------------------------------------------- run --- */

async function main() {
  const redirects = JSON.parse(await fs.readFile('data/redirects.json', 'utf8'));
  await fs.mkdir(DEPLOY, { recursive: true });
  await fs.mkdir(DIST, { recursive: true });

  const outputs = {
    '_redirects': netlify(redirects),
    '_headers': headersFile(),
  };

  // Netlify and Cloudflare Pages both read _redirects/_headers from the
  // publish directory, so those go into dist as well as deploy.
  for (const [name, body] of Object.entries(outputs)) {
    await fs.writeFile(path.join(DIST, name), body);
    await fs.writeFile(path.join(DEPLOY, name), body);
  }

  await fs.writeFile(path.join(DEPLOY, 'vercel.json'), vercel(redirects));
  await fs.writeFile(path.join(DEPLOY, 'cloudflare-pages_redirects'), cloudflare(redirects));
  await fs.writeFile(path.join(DEPLOY, 'redirects.htaccess'), apache(redirects));
  await fs.writeFile(path.join(DEPLOY, 'redirects.nginx.conf'), nginx(redirects));

  const esc = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
  await fs.writeFile(
    path.join(DEPLOY, 'redirects.csv'),
    ['source,target,status', ...redirects.map((r) => [r.from, r.to, r.status].map(esc).join(','))].join('\n')
  );

  const queryBased = redirects.filter((r) => r.from.includes('?')).length;
  console.log(`redirects: ${redirects.length} rules (${queryBased} query-string based)`);
  console.log('  dist/_redirects, dist/_headers');
  console.log('  deploy/{_redirects,_headers,vercel.json,cloudflare-pages_redirects,redirects.htaccess,redirects.nginx.conf,redirects.csv}');
}

main();
